# Наценка на станки. Решение от 31.07.2026: цены всех станков поднимаются
# на 5 % к прайсу с округлением до 100 ₽ вверх при половине. Поднимаются
# ТОЛЬКО станки: волокно (A, S, S-Bochu), фрезерные, CO₂, маркираторы.
